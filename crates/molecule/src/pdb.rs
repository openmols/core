//! PDB / mmCIF loading through `pdbtbx`.

use crate::{Atom, Element, Residue, Structure, perceive_bonds};
use anyhow::{Result, anyhow};
use glam::Vec3;
use pdbtbx::{ReadOptions, StrictnessLevel};
use std::path::Path;

/// Make a PDB acceptable to a strict reader without changing its structure.
///
/// Two things real files get wrong:
/// * Lines stop at column 66 with no element, as FRODOCK's poses and
///   pyKVFinder's cavity grids do. Those are padded and given an element
///   guessed from the atom name.
/// * `REMARK` carries free text instead of a remark number, as GROMACS
///   `trjconv` writes (`REMARK    GENERATED BY TRJCONV`). openmols reads
///   nothing from remarks, so those lines are dropped.
pub fn pad_short_atom_lines(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + text.len() / 16);
    let mut chains = ChainSplitter::default();
    for line in text.lines() {
        // openmols reads nothing from remarks, and writers disagree about the
        // remark-number field, so drop them rather than fail on them. MASTER
        // is a checksum over those record counts, so it has to go as well.
        if line.starts_with("REMARK") || line.starts_with("MASTER") {
            continue;
        }
        // Each model repeats the same atoms, so the splitter starts over at a
        // model boundary. Carrying its state across would relabel the second
        // and later models differently from the first, and a reader that
        // matches models atom by atom then rejects the file.
        if line.starts_with("MODEL") || line.starts_with("ENDMDL") {
            chains = ChainSplitter::default();
        }
        let is_atom = line.starts_with("ATOM") || line.starts_with("HETATM");
        let relabelled = is_atom.then(|| chains.relabel(line)).flatten();
        let line: &str = relabelled.as_deref().unwrap_or(line);
        if is_atom && line.len() >= 54 && line.len() < 78 {
            let name = line.get(12..16).unwrap_or("").to_string();
            let element = Element::guess_from_atom_name(&name);
            let symbol = if element == Element::UNKNOWN { "" } else { element.symbol() };
            out.push_str(&format!("{:<76}{:>2}", &line[..line.len().min(76)], symbol.to_uppercase()));
        } else {
            out.push_str(line);
        }
        out.push('\n');
    }
    out
}

/// Gives each copy of a repeated molecule its own chain id.
///
/// Some writers put every copy of an oligomer on one chain and restart the
/// residue numbering for each (24 chains of an amyloid fibril all labelled
/// `A`, numbered 1-42 over and over). A reader then merges them and residue
/// "25" stops identifying anything. When a residue id reappears, the copy is
/// moved to the next free chain letter instead.
#[derive(Default)]
struct ChainSplitter {
    /// Residue ids already written on the current chain.
    seen: std::collections::HashSet<(char, i64, char)>,
    current: Option<(char, i64, char)>,
    /// Chain to write instead of the original, once a split has happened.
    replacement: Option<char>,
    used: std::collections::HashSet<char>,
}

impl ChainSplitter {
    /// `None` when the line needs no change.
    fn relabel(&mut self, line: &str) -> Option<String> {
        let chain = line.as_bytes().get(21).copied().map(char::from)?;
        let number: i64 = line.get(22..26)?.trim().parse().ok()?;
        let icode = line.as_bytes().get(26).copied().map(char::from).unwrap_or(' ');
        let residue = (chain, number, icode);

        if self.current != Some(residue) {
            // A residue id we have already written means the molecule has
            // started over, so this copy gets a chain of its own.
            if self.seen.contains(&residue) {
                self.replacement = Some(self.next_chain(chain));
                self.seen.clear();
            }
            self.current = Some(residue);
            self.seen.insert(residue);
        }

        let replacement = self.replacement?;
        let mut bytes = line.as_bytes().to_vec();
        bytes[21] = replacement as u8;
        String::from_utf8(bytes).ok()
    }

    fn next_chain(&mut self, original: char) -> char {
        self.used.insert(original);
        if let Some(previous) = self.replacement {
            self.used.insert(previous);
        }
        ('A'..='Z')
            .chain('a'..='z')
            .chain('0'..='9')
            .find(|c| !self.used.contains(c))
            .unwrap_or(original)
    }
}

/// Split a PDB that holds several conformations separated by bare `END`
/// records, as GROMACS `trjconv` and several ensemble writers produce.
///
/// Returns one slice per frame. A file that uses proper `MODEL` records, or
/// holds a single structure, comes back as a single slice and is left to
/// pdbtbx.
pub fn split_end_delimited(text: &str) -> Vec<&str> {
    if text.contains("\nMODEL ") || text.starts_with("MODEL ") {
        return vec![text];
    }
    let mut blocks = Vec::new();
    let mut start = 0usize;
    let mut has_atoms = false;
    let mut offset = 0usize;
    for line in text.split_inclusive('\n') {
        let end = offset + line.len();
        let trimmed = line.trim_end();
        if trimmed.starts_with("ATOM") || trimmed.starts_with("HETATM") {
            has_atoms = true;
        }
        // "END" ends a frame; "ENDMDL" and "ENDCHN" are different records.
        if trimmed == "END" && has_atoms {
            blocks.push(&text[start..end]);
            start = end;
            has_atoms = false;
        }
        offset = end;
    }
    if has_atoms {
        blocks.push(&text[start..]);
    }
    if blocks.len() <= 1 { vec![text] } else { blocks }
}

/// Coordinates of the `ATOM`/`HETATM` lines in one block, in file order.
fn block_coordinates(block: &str) -> Vec<Vec3> {
    block
        .lines()
        .filter(|l| l.starts_with("ATOM") || l.starts_with("HETATM"))
        .filter_map(|l| {
            let number = |range: std::ops::Range<usize>| l.get(range)?.trim().parse::<f32>().ok();
            Some(Vec3::new(number(30..38)?, number(38..46)?, number(46..54)?))
        })
        .collect()
}

pub fn load(path: &Path) -> Result<Structure> {
    let path_str = path.to_string_lossy();
    // mmCIF and compressed files go to pdbtbx untouched; plain PDB text is
    // normalised first so tool output with short lines still loads.
    let lower = path_str.to_lowercase();

    // Conformations separated by bare END records: parse the first for the
    // topology and take coordinates from the rest. Letting pdbtbx build every
    // model would cost far more memory on a large ensemble.
    //
    // The file text is read inside this block so that it is freed before
    // parsing and bond perception. A 1000-frame trajectory is over a
    // gigabyte, and holding it alongside the coordinates doubles the peak.
    let mut extra_frames: Vec<Vec<Vec3>> = Vec::new();
    let padded = {
        let text = crate::is_pdb_like(&lower)
            .then(|| std::fs::read_to_string(path).ok())
            .flatten();
        text.as_deref().map(|text| {
            let blocks = split_end_delimited(text);
            if blocks.len() > 1 {
                extra_frames = blocks[1..].iter().map(|b| block_coordinates(b)).collect();
            }
            pad_short_atom_lines(blocks[0])
        })
    };

    // pdbtbx can panic on unusual input (e.g. negative occupancies); never let
    // a bad file take the application down.
    let read = std::panic::catch_unwind(|| match &padded {
        Some(text) => ReadOptions::new()
            .set_format(pdbtbx::Format::Pdb)
            .set_level(StrictnessLevel::Loose)
            .read_raw(std::io::BufReader::new(std::io::Cursor::new(text.as_bytes()))),
        None => ReadOptions::new()
            .guess_format(&path_str)
            .set_level(StrictnessLevel::Loose)
            .read(&path_str),
    })
    .map_err(|panic| {
        let reason = panic
            .downcast_ref::<String>()
            .cloned()
            .or_else(|| panic.downcast_ref::<&str>().map(|s| s.to_string()))
            .unwrap_or_else(|| "parser panicked".into());
        anyhow!("failed to read {}: {reason}", path.display())
    })?;
    let (pdb, _warnings) = read.map_err(|errors| {
        let msg = errors
            .iter()
            .map(|e| e.to_string())
            .collect::<Vec<_>>()
            .join("\n");
        anyhow!("failed to read {}:\n{msg}", path.display())
    })?;

    let mut structure = Structure {
        name: pdb.identifier.clone().unwrap_or_default(),
        ..Default::default()
    };

    let Some(model) = pdb.model(0) else {
        return Ok(structure);
    };

    // Traversal shared by the topology pass and the extra-model pass, so atom
    // order is identical across models.
    fn model_atoms(model: &pdbtbx::Model) -> impl Iterator<Item = &pdbtbx::Atom> {
        model.chains().flat_map(|chain| {
            chain
                .residues()
                .filter_map(|r| r.conformers().next())
                .flat_map(|c| c.atoms())
        })
    }

    for chain in model.chains() {
        for residue in chain.residues() {
            // Keep only the first alternate conformer of each residue.
            let Some(conformer) = residue.conformers().next() else {
                continue;
            };
            let (number, insertion_code) = residue.id();
            let residue_index = structure.residues.len() as u32;
            let first_atom = structure.atoms.len() as u32;
            structure.residues.push(Residue {
                name: conformer.name().to_string(),
                number,
                insertion_code: insertion_code.map(str::to_string),
                chain: chain.id().to_string(),
                atoms: first_atom..first_atom,
            });
            for atom in conformer.atoms() {
                let (x, y, z) = atom.pos();
                let element = atom
                    .element()
                    .map(|e| Element::from_symbol(e.symbol()))
                    .filter(|e| *e != Element::UNKNOWN)
                    .unwrap_or_else(|| Element::guess_from_atom_name(atom.name()));
                structure.atoms.push(Atom {
                    name: atom.name().to_string(),
                    element,
                    position: Vec3::new(x as f32, y as f32, z as f32),
                    residue: residue_index,
                    hetero: atom.hetero(),
                    serial: atom.serial_number(),
                    b_factor: atom.b_factor() as f32,
                });
            }
            structure.residues[residue_index as usize].atoms.end = structure.atoms.len() as u32;
        }
    }

    // Further models (NMR ensembles, multi-model trajectories) become frames
    // when they have the same atoms as the first model.
    if pdb.model_count() > 1 {
        let mut frames = vec![structure.atoms.iter().map(|a| a.position).collect::<Vec<_>>()];
        for extra in pdb.models().skip(1) {
            let positions: Vec<Vec3> = model_atoms(extra)
                .map(|a| {
                    let (x, y, z) = a.pos();
                    Vec3::new(x as f32, y as f32, z as f32)
                })
                .collect();
            if positions.len() == structure.atoms.len() {
                frames.push(positions);
            }
        }
        if frames.len() > 1 {
            structure.frames = frames;
        }
    }

    // Conformations that were separated by END records. Blocks whose atom
    // count differs from the first are skipped rather than mangling the
    // topology.
    if !extra_frames.is_empty() {
        let expected = structure.atoms.len();
        let mut frames = vec![structure.atoms.iter().map(|a| a.position).collect::<Vec<_>>()];
        frames.extend(extra_frames.into_iter().filter(|f| f.len() == expected));
        if frames.len() > 1 {
            structure.frames = frames;
        }
    }

    structure.bonds = perceive_bonds(&structure.atoms);
    Ok(structure)
}
